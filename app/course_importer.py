class _TextExtractor(HTMLParser):
    HIDDEN = {"script", "style", "noscript", "svg", "nav", "footer", "header"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.hidden = 0
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag in self.HIDDEN:
            self.hidden += 1
        if not self.hidden and tag in {"p", "li", "h1", "h2", "h3", "br", "tr"}:
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if tag in self.HIDDEN and self.hidden:
            self.hidden -= 1

    def handle_data(self, data):
        if not self.hidden and data.strip():
            self.parts.append(data.strip())


def _plain_html(path):
    parser = _TextExtractor()
    try:
        parser.feed(path.read_text(encoding="utf-8", errors="replace"))
    except OSError:
        return ""
    text = re.sub(r"[ \t\xa0]+", " ", " ".join(parser.parts))
    return re.sub(r"\n\s*\n+", "\n", text).strip()[:18000]


def _clean_title(value):
    value = Path(value).stem
    value = re.sub(r"^\s*\[[^]]+\]\s*", "", value)
    value = re.sub(r"^\d+[ ._-]*", "", value)
    value = re.sub(r"\s+", " ", value).strip(" ._-–")
    return value[:180] or "Урок"


def _natural(path):
    return [int(part) if part.isdigit() else part.casefold() for part in re.split(r"(\d+)", str(path))]


def _question(prompt, options, correct=0, explanation=""):
    options = list(options)
    answer = options[correct]
    random.SystemRandom().shuffle(options)
    return {"prompt": prompt, "options": options, "correct": options.index(answer), "explanation": explanation}


