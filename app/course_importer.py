def _upsert_course(title, category, description, level, duration, icon, color):
    course = Course.query.filter_by(title=title).first()
    if course is None:
        course = Course(title=title, category=category)
        db.session.add(course)
    course.category = category
    course.description = description
    course.level = level
    course.duration = duration
    course.icon = icon
    course.color = color
    course.course_type = "course"
    course.published = True
    db.session.flush()
    return course


def _existing_titles(course):
    return {f"{lesson.module_name}\x00{lesson.title}" for lesson in course.lessons}


def _add_lesson(course, title, module, position, video_path=None, content="", quiz=None, resources=None, existing=None):
    existing = existing if existing is not None else _existing_titles(course)
    unique_key = f"{module}\x00{title}"
    if unique_key in existing:
        return False
    lesson = Lesson(
        course=course,
        title=title[:180],
        module_name=module[:180],
        position=position,
        video_url=f"local:{video_path}" if video_path else None,
        content=content[:18000],
        quiz_data=quiz,
        resources_json=resources or None,
    )
    db.session.add(lesson)
    existing.add(unique_key)
    return True


def _quiz_lesson(course, module, position, existing):
    questions = QUIZZES.get(course.title, {}).get(module)
    if not questions:
        return False
    title = f"Проверка знаний · {module}"[:180]
    return _add_lesson(course, title, module, position, content="Ответьте на вопросы, чтобы закрепить ключевые понятия раздела.", quiz=questions, existing=existing)


def _module_dirs(root):
    return sorted((p for p in root.iterdir() if p.is_dir()), key=_natural)


RESOURCE_SUFFIXES = {".html", ".txt", ".py", ".md", ".pdf", ".ipynb", ".zip", ".gz", ".tar", ".png", ".yml", ".yaml"}


def _lesson_resources(video_path, module_dir, media_root):
    stem = re.sub(r"^\s*\[[^]]+\]\s*", "", video_path.stem)
    match = re.match(r"\s*(\d+)", stem)
    if not match:
        return []
    number = match.group(1).lstrip("0") or "0"
    resources = []
    for path in sorted(module_dir.rglob("*"), key=_natural):
        if not path.is_file() or path.suffix.lower() not in RESOURCE_SUFFIXES:
            continue
        if path.name.startswith(".") or ".DS_Store" in path.parts:
            continue
        file_stem = re.sub(r"^\s*\[[^]]+\]\s*", "", path.stem)
        file_match = re.match(r"\s*(\d+)", file_stem)
        parent_match = re.match(r"\s*(\d+)", path.parent.name)
        if (file_match and (file_match.group(1).lstrip("0") or "0") == number) or (parent_match and (parent_match.group(1).lstrip("0") or "0") == number):
            resources.append({"name": path.name[:180], "path": path.relative_to(media_root).as_posix()})
    return resources


def _import_ai(root):
    folder = next((p for p in _module_dirs(root) if p.name.startswith("[Stepik] AI Developer") and not p.name.endswith(" 2")), None)
    if folder is None:
        raise click_error("Не найден курс AI Developer в папке 1")
    course = _upsert_course(*COURSE_META["1"])
    existing = _existing_titles(course)
    position = 0
    module_dirs = _module_dirs(folder)
    module_names = QUIZZES[course.title]
    imported = 0
    for module_dir in module_dirs:
        module = next((name for name in module_names if module_dir.name.startswith(name.split(". ", 1)[0] + ".")), module_dir.name)
        for html in sorted(module_dir.rglob("*.html"), key=_natural):
            if html.name.casefold().startswith("программа курса"):
                continue
            position += 1
            title = _clean_title(html.name)
            if f"{module}\x00{title}" in existing:
                continue
            content = _plain_html(html)
            imported += int(_add_lesson(course, title, module, position, content=content, existing=existing))
        if module in module_names:
            position += 1
            imported += int(_quiz_lesson(course, module, position, existing))
    return course, imported


